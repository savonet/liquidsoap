let capitalize = String.capitalize_ascii

let () =
  print_string
    "; Generated by gen_dune.ml, do not edit.\n\
     ; Regenerate with: dune build @gendune --auto-promote\n";

  List.iter
    (fun { prefix; requires; _ } ->
      Printf.printf
        {|
(rule
 (target %s_option.enabled.ml)
 (action
  (with-stdout-to
   %%{target}
   (echo "let enabled = true\nlet detected = \"yes\"\n"))))

(rule
 (target %s_option.disabled.ml)
 (action
  (with-stdout-to
   %%{target}
   (echo "let enabled = false\nlet detected = \"no (requires %s)\"\n"))))
|}
        prefix prefix requires)
    deps;

  (* The list behind liquidsoap.build_config.optionals.*, so that the set of
     reported dependencies cannot drift from the set that is selected. *)
  Printf.printf
    {|
(rule
 (target optionals_build_config.ml)
 (action
  (with-stdout-to
   %%{target}
   (progn
    (echo "let all = [\n")
|};
  List.iter
    (fun { prefix; build_config; _ } ->
      match build_config with
        | None -> ()
        | Some name ->
            Printf.printf
              "    (echo \"  (\\\"%s\\\", %s_option.enabled);\\n\")\n" name
              (capitalize prefix))
    deps;
  print_string "    (echo \"]\\n\")))))\n";

  print_string
    {|
(library
 (name liquidsoap_optionals)
 (preprocess
  (pps ppx_string))
 (wrapped false)
 (modules
  (:standard \ gen_dune))
 (flags
  (:standard -open Liquidsoap_core))
 (libraries
  liquidsoap_core
|};
  List.iter
    (fun { prefix; library; _ } ->
      Printf.printf
        "  (select\n\
        \   %s_option.ml\n\
        \   from\n\
        \   (%s -> %s_option.enabled.ml)\n\
        \   (-> %s_option.disabled.ml))\n"
        prefix library prefix prefix)
    deps;
  print_string "  ))\n"
