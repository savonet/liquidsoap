(* Generates dune.inc: the liquidsoap_optionals library stanza, and the pair of
   modules that (select ...) picks between for each optional dependency.

   Adding an optional dependency is one line in [deps] below, then:
     dune build @gendune --auto-promote

   Fields: the module prefix (<prefix>_option.ml is what build_config.ml
   interpolates), the dune library whose availability decides the select, the
   name to print when it is missing, and the name it is reported under in
   liquidsoap.build_config.optionals -- [None] for the ones that are not
   reported there. *)

type dep = {
  prefix : string;
  library : string;
  requires : string;
  build_config : string option;
}

let dep ?build_config ?requires prefix library =
  let requires = Option.value ~default:prefix requires in
  { prefix; library; requires; build_config }

